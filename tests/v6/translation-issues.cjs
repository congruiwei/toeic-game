const assert=require('node:assert/strict');
const fs=require('node:fs/promises');
module.exports=async({page,quiz,act,state,reset})=>{
  await quiz('grammar');await act('unknown');
  const id=(await state()).session.items[0].id;
  await act('translate');
  await page.locator('.lesson-feedback > .translations [lang=ja]').first().waitFor();
  await act('report-issue');
  await page.selectOption('#issue-reason','翻译不自然');
  assert.match(await page.locator('#issue-note').getAttribute('placeholder'),/哪一句.*中文或日语/);
  const note='日语 · 完整句子的请求语气：请核对敬语是否符合场景。';
  await page.fill('#issue-note',note);await act('save-issue');
  const report=(await state()).issues[0];
  assert.equal(report.id,id);assert.equal(report.reason,'翻译不自然');assert.equal(report.note,note);
  assert.match(report.text,/题干/);assert.match(report.text,/正确答案/);
  await page.reload();await act('settings');
  assert.match(await page.locator('dialog').innerText(),/问题报告（1）/);
  await page.evaluate(()=>Object.defineProperty(navigator,'clipboard',{configurable:true,value:{writeText:async()=>{throw Error('denied');}}}));
  await act('copy-issues');
  const copied=await page.locator('#copy-fallback').inputValue();
  assert(copied.includes('翻译不自然')&&copied.includes(note)&&copied.includes(report.text));
  await act('close');await act('settings');
  const downloading=page.waitForEvent('download');await act('export');
  const downloaded=await downloading;
  const backup=await fs.readFile(await downloaded.path());
  assert.deepEqual(JSON.parse(backup).issues,[report]);
  await reset();await act('settings');
  await page.locator('#import-file').setInputFiles({name:'translation-report.json',mimeType:'application/json',buffer:backup});
  await act('restore');assert.deepEqual((await state()).issues,[report]);
};
